export function getRoomsByMarket(market: MarketCode): Room[] {
  const local = getLocalRooms().filter((r) => r.market === market);
  return [...allRooms.filter((r) => r.market === market), ...local];
}

export function getLocalRooms(): Room[] {
  try {
    return JSON.parse(localStorage.getItem('ilehya-rooms') || '[]');
  } catch { return []; }
}

export function getVilles(market: MarketCode): string[] {
  return [...new Set(getRoomsByMarket(market).map((r) => r.ville))].sort();
}

export function getQuartiers(market: MarketCode): string[] {
  return [...new Set(getRoomsByMarket(market).map((r) => r.quartier))].sort();
}
